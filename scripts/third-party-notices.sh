#!/usr/bin/env sh
# Writes THIRD_PARTY_NOTICES.md: the licence of every Go module compiled into
# mangarr and mangarr-worker, every npm package in the web bundle, and the
# tools the full image and the worker zips bundle. Run it after dependency
# updates and before a release; it needs Go and web/node_modules (npm ci).
#
#   scripts/third-party-notices.sh > THIRD_PARTY_NOTICES.md
set -eu
cd "$(dirname "$0")/.."
[ -d web/node_modules ] || { echo "web/node_modules is missing: run npm ci in web/ first" >&2; exit 1; }

spdx() { # licence file -> SPDX id, from its wording
  t=$(tr '\n' ' ' < "$1")
  case "$t" in
    *"Apache License"*) echo Apache-2.0 ;;
    *"ISC License"*|*"Permission to use, copy, modify, and/or distribute"*) echo ISC ;;
    *"Redistribution and use"*)
      case "$t" in
        *"Neither the name"*|*"names of its contributors"*|*"name of the copyright holder"*) echo BSD-3-Clause ;;
        *) echo BSD-2-Clause ;;
      esac ;;
    *"Permission is hereby granted"*) echo MIT ;;
    *) echo "see text" ;;
  esac
}
licfile() { ls "$1" | grep -i -E '^(licen[cs]e|copying)' | head -1; }

cat <<'EOF'
# Third-party notices

mangarr is licensed under AGPL-3.0-or-later (see `LICENSE`). It includes
the software listed below, each under its own licence, whose text follows.
`internal/chapternum` is a port of Mihon's chapter recognition
(Apache-2.0, https://github.com/mihonapp/mihon).

This file is generated by `scripts/third-party-notices.sh`.

## Bundled tools

The full image (amd64) and the desktop worker zips bundle these programs and
models unchanged, as the projects publish them:

| Program | Licence | Source |
|---|---|---|
| waifu2x-ncnn-vulkan, with waifu2x models | MIT | https://github.com/nihui/waifu2x-ncnn-vulkan, https://github.com/nagadomi/waifu2x |
| realcugan-ncnn-vulkan, with Real-CUGAN models | MIT | https://github.com/nihui/realcugan-ncnn-vulkan, https://github.com/bilibili/ailab |
| realesrgan-ncnn-vulkan | MIT | https://github.com/xinntao/Real-ESRGAN-ncnn-vulkan |
| Real-ESRGAN models | BSD-3-Clause | https://github.com/xinntao/Real-ESRGAN |
| ncnn (linked into the upscalers) | BSD-3-Clause | https://github.com/Tencent/ncnn |
| avifenc (libavif) | BSD-2-Clause | https://github.com/AOMediaCodec/libavif |
| cwebp (libwebp), worker zips | BSD-3-Clause | https://chromium.googlesource.com/webm/libwebp |
| cjxl (libjxl), Linux worker zip | BSD-3-Clause | https://github.com/libjxl/libjxl |

The full image also installs Debian packages (Vulkan and Mesa drivers,
webp, libavif-bin, libjxl-tools, libjpeg-progs), whose licences are in the
image under `/usr/share/doc`. The AVIF and WebP encoders built into mangarr
(`github.com/gen2brain/avif`, `github.com/gen2brain/webp`) embed libavif,
libaom and libwebp compiled to WebAssembly, all BSD licensed.

## Go modules

| Module | Version | Licence |
|---|---|---|
EOF
echo "| Go standard library | $(go env GOVERSION) | BSD-3-Clause |"

mods=$(CGO_ENABLED=0 go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/... | sort -u)
echo "$mods" | while read -r path version dir; do
  echo "| $path | $version | $(spdx "$dir/$(licfile "$dir")") |"
done

cat <<'EOF'

## Web packages

| Package | Version | Licence |
|---|---|---|
EOF

# production dependencies only: the lockfile marks dev-only packages
web=$(cd web && node -e '
  const lock = require("./package-lock.json").packages;
  for (const [k, p] of Object.entries(lock)) {
    if (!k || p.dev) continue;
    console.log(k.replace(/^.*node_modules\//, ""), p.version, k);
  }' | sort -u)
echo "$web" | while read -r name version dir; do
  echo "| $name | $version | $(spdx "web/$dir/$(licfile "web/$dir")") |"
done

echo
echo "## Licence texts"
printf '\n### Go standard library\n\n```\n'
goroot=$(go env GOROOT) # Homebrew keeps it one level up
cat "$goroot/LICENSE" 2>/dev/null || cat "$goroot/../LICENSE"
printf '```\n'
echo "$mods" | while read -r path version dir; do
  printf '\n### %s\n\n```\n' "$path"
  cat "$dir/$(licfile "$dir")"
  printf '```\n'
done
echo "$web" | while read -r name version dir; do
  printf '\n### %s\n\n```\n' "$name"
  cat "web/$dir/$(licfile "web/$dir")"
  printf '```\n'
done
