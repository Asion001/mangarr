CREATE VIEW chapter_read_states AS
 SELECT t.id,
    t.reader_id,
    c.id AS chapter_id,
    c.series_id,
    t.completed,
    t.page,
    t.read_at,
    t.synced_at,
    t.origin,
    t.chapter_id AS source_chapter_id
   FROM ((title_read_states t
     JOIN series s ON ((COALESCE(s.work_id, (- s.id)) = t.title_id)))
     JOIN chapters c ON (((c.series_id = s.id) AND (c.number_key = t.number_key))));

